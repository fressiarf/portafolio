// Convierte las filas en rectangulos, uniendo pixeles contiguos del mismo color.
export function spriteRects(rows, palette) {
  const rects = []
  rows.forEach((row, y) => {
    let x = 0
    while (x < row.length) {
      const ch = row[x]
      let end = x + 1
      while (end < row.length && row[end] === ch) end++
      const fill = palette[ch]
      if (fill) rects.push({ x, y, w: end - x, fill, ch })
      x = end
    }
  })
  return rects
}
